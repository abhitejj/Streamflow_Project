#!/usr/bin/env python3
"""Package the saved forecast rows as one static chunk per gauge and lead."""

import argparse
import csv
import hashlib
import json
import math
from datetime import date, timedelta
from pathlib import Path

from export_explorer_data import DROUGHT, FLOW, RESULTS, ROOT, load_results, number, source


PREDICTIONS = RESULTS / "test_predictions.csv"
STATIONS = ROOT / "assets/benchmark-data.js"
MODELS = {"M0": "m0", "M1": "m1_gbt", "M2": "m2_gbt", "M1-log": "m1_gbt_log", "M2-log": "m2_gbt_log"}
FIELDS = ["issue_date", "target_date", "scored", "zero_as_missing", "observed", *MODELS]
TEST_END = "2025-12-31"


def compact(data):
    return json.dumps(data, sort_keys=True, separators=(",", ":"), allow_nan=False)


def build(assets):
    audited = load_results()
    metadata, _ = json.JSONDecoder().raw_decode(STATIONS.read_text().split("window.STATIONS = ", 1)[1])
    station_ids = {str(row["camels_id"]): row["id"] for row in metadata}
    with FLOW.open(newline="") as file:
        gauges = {row["station"]: row["gauge_id"] for row in csv.DictReader(file)}
    groups = {(gauge, lead): [] for gauge, horizons in audited.items() for lead in horizons}
    with PREDICTIONS.open(newline="") as file:
        for row in csv.DictReader(file):
            gauge, lead = gauges[row["station"]], row["horizon"]
            issue, target = row["issue_date"], row["target_date"]
            if date.fromisoformat(target) - date.fromisoformat(issue) != timedelta(weeks=int(lead[:-1])):
                raise ValueError(f"Invalid target date for gauge {gauge} {lead} {issue}")
            scored, zero = row["scored"] == "True", row["zero_as_missing"] == "True"
            values = [number(row[column]) for column in ("y_obs", *MODELS.values())]
            if scored and (zero or target > TEST_END or not all(v is not None and math.isfinite(v) for v in values)):
                raise ValueError(f"Invalid scored forecast for gauge {gauge} {lead} {target}")
            groups[gauge, lead].append([issue, target, scored, zero, *values])

    chunks = {}
    replay = assets / "replay"
    replay.mkdir(parents=True, exist_ok=True)
    for (gauge, lead), rows in sorted(groups.items()):
        station = station_ids[gauge]
        rows.sort(key=lambda row: row[1])
        entry = audited[gauge][lead]
        if not rows or len({row[1] for row in rows}) != len(rows) or sum(row[2] for row in rows) != entry["n_eval"]:
            raise ValueError(f"Incomplete or duplicate predictions for {station} {lead}")
        data = {"station": station, "lead": lead, "rows": rows,
                "thresholds": {severity: group["threshold"] for severity, group in entry["drought"].items()}}
        payload = (compact(data) + "\n").encode()
        digest = hashlib.sha256(payload).hexdigest()
        name = f"{station}-{lead}.json"
        (replay / name).write_bytes(payload)
        chunks.setdefault(station, {})[lead] = {"file": f"replay/{name}", "sha256": digest}
    manifest = {"schema": 1, "fields": FIELDS, "test_end": TEST_END, "chunks": chunks,
                "sources": {"predictions": source(PREDICTIONS), "thresholds": source(DROUGHT)}}
    (assets / "replay-manifest.js").write_text("/* Generated by scripts/export_replay_data.py. */\nwindow.REPLAY_DATA = " + compact(manifest) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets-dir", type=Path, default=ROOT / "site/assets")
    build(parser.parse_args().assets_dir)
