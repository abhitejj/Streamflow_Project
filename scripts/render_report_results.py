def splice(path: Path, start: str, end: str, body: str) -> None:
    s = path.read_text()
    i, j = s.index(start) + len(start), s.index(end)
    path.write_text(s[:i] + "\n" + body + "\n" + s[j:])
    print(f"[+] Updated {path.relative_to(ROOT)}")


